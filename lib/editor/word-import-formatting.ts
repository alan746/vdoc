const W = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main';
const elements = (parent: Element | Document, name: string) => Array.from(parent.getElementsByTagNameNS(W, name));
const attr = (el: Element | null | undefined, name = 'val') => el?.getAttributeNS(W, name) || undefined;
const first = (parent: Element | undefined, name: string) => parent ? elements(parent, name)[0] : undefined;
const child = (parent: Element | undefined, name: string) => parent ? Array.from(parent.children).find(node => node.namespaceURI === W && node.localName === name) : undefined;
const validHex = (value: string | undefined) => value && /^[\da-f]{6}$/i.test(value) ? `#${value}` : undefined;
const wordText = (el: Element) => Array.from(el.getElementsByTagNameNS(W, '*')).map(n => n.localName === 't' ? n.textContent || '' : n.localName === 'tab' && n.parentElement?.localName === 'r' ? '\t' : '').join('');

// Mammoth understands w:br but omits the equivalent w:cr carriage return.
// Normalize before conversion so breaks retain their exact position among links
// and references; reconstructing their positions from plain text is ambiguous.
export async function normalizeWordCarriageReturns(buffer: ArrayBuffer): Promise<ArrayBuffer> {
  const zip = await JSZip.loadAsync(buffer);
  let changed = false;
  for (const path of ['word/document.xml', 'word/footnotes.xml']) {
    const raw = await zip.file(path)?.async('string');
    if (!raw) continue;
    if (raw.length > 20_000_000) throw new Error('The Word document is too large to import.');
    if (!/<(?:[\w.-]+:)?cr(?:\s|\/|>)/.test(raw)) continue;
    const xml = new DOMParser().parseFromString(raw, 'application/xml');
    const breaks = elements(xml, 'cr');
    if (!breaks.length) continue;
    for (const node of breaks) node.replaceWith(xml.createElementNS(W, 'w:br'));
    zip.file(path, new XMLSerializer().serializeToString(xml));
    changed = true;
  }
  return changed ? zip.generateAsync({ type: 'arraybuffer' }) : buffer;
}

// Footnote reference labels are generated by Mammoth, not body text in w:r.
// Keep links, breaks, and reference nodes in place while matching text offsets.
function inlineTextNodes(parent: Element): Text[] {
  const walker = parent.ownerDocument.createTreeWalker(parent, 4);
  const nodes: Text[] = [];
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (!node.parentElement?.closest('a[href^="#footnote-"]:not([href^="#footnote-ref-"])')) nodes.push(node as Text);
  }
  return nodes;
}
const inlineText = (parent: Element) => inlineTextNodes(parent).map(node => node.data).join('');
function restoreInlineRuns(html: Document, target: Element, runs: Element[], render: (run: Element, text: string) => DocumentFragment): boolean {
  const parts = runs.map(run => ({ run, text: wordText(run) })).filter(part => part.text);
  const nodes = inlineTextNodes(target);
  // Validate the entire mapping before touching the converted structure.
  if (parts.map(part => part.text).join('') !== nodes.map(node => node.data).join('')) return false;
  // Replace converted presentation wrappers after matching all text. Keeping old
  // wrappers would reapply a style even when the current run explicitly turns it off.
  for (const wrapper of Array.from(target.querySelectorAll('strong,b,em,i,u,s,strike,span,mark,sub,sup')).reverse()) {
    if (wrapper.closest('a[href^="#footnote-"]') || wrapper.querySelector('a[href^="#footnote-"]')) continue;
    wrapper.replaceWith(...Array.from(wrapper.childNodes));
  }
  let partIndex = 0, partOffset = 0;
  for (const node of nodes) {
    let offset = 0;
    const fragment = html.createDocumentFragment();
    while (offset < node.length) {
      const part = parts[partIndex];
      const size = Math.min(node.length - offset, part.text.length - partOffset);
      fragment.append(render(part.run, node.data.slice(offset, offset + size)));
      offset += size; partOffset += size;
      if (partOffset === part.text.length) { partIndex++; partOffset = 0; }
    }
    if (node.length) node.replaceWith(fragment);
  }
  return true;
}

/** Restore formatting, inherited paragraph layout and numbering omitted by Mammoth. */
export async function restoreWordFormatting(buffer: ArrayBuffer, html: Document, warnings: string[] = []) {
  // Mammoth emits simple list paragraphs as bare li text. Materialize the paragraph
  // before matching Word pPr, otherwise spacing/indentation/formatting is discarded.
  html.querySelectorAll('li:not([id^="footnote-"])').forEach(item=>{
    let inline:ChildNode[]=[];
    const flush=()=>{
      if(!inline.length)return;
      if(inline.some(n=>n.nodeType===1 || n.textContent?.length)) {
        const p=html.createElement('p');item.insertBefore(p,inline[0]);inline.forEach(n=>p.appendChild(n));
      }
      inline=[];
    };
    Array.from(item.childNodes).forEach(node=>{
      if(node instanceof Element && /^(P|H[1-6]|UL|OL|TABLE|BLOCKQUOTE|PRE|DIV|HR)$/.test(node.tagName))flush();else inline.push(node);
    });flush();
    // Empty numbered paragraphs are emitted as bare li nodes by Mammoth.
    // Materialize their leading paragraph before numbering/text matching too.
    if (!item.firstElementChild || !/^(P|H[1-6])$/.test(item.firstElementChild.tagName)) {
      item.insertBefore(html.createElement('p'), item.firstChild);
    }
  });
  const zip = await JSZip.loadAsync(buffer);
  const raw = await zip.file('word/document.xml')?.async('string');
  if (!raw) return {};
  if (raw.length > 20_000_000) throw new Error('The Word document is too large to import.');
  const stylesRaw = await zip.file('word/styles.xml')?.async('string');
  const styles = stylesRaw ? new DOMParser().parseFromString(stylesRaw, 'application/xml') : null;
  const paragraphProperties = wordParagraphProperties(styles, warnings);
  const defaults = styles ? elements(styles, 'docDefaults')[0] : undefined;
  const defaultLanguage = first(first(first(defaults, 'rPrDefault'), 'rPr'), 'lang');
  const language = canonicalLanguage(attr(defaultLanguage) || attr(defaultLanguage, 'eastAsia') || attr(defaultLanguage, 'bidi')) || 'und';
  const xml = new DOMParser().parseFromString(raw, 'application/xml');
  const settingsRaw = await zip.file('word/settings.xml')?.async('string');
  const settings = settingsRaw ? new DOMParser().parseFromString(settingsRaw, 'application/xml') : null;
  const theme = await wordTheme(zip, settings, warnings);
  const formatRun = wordRunFormatter(styles, theme, warnings);
  const defaultTabs = settings ? Number(attr(elements(settings, 'defaultTabStop')[0])) / 15 : DEFAULT_TAB_INTERVAL;
  const defaultInterval = validTabInterval(defaultTabs) ? defaultTabs : DEFAULT_TAB_INTERVAL;
  const warnTabs = () => { const message = 'Some custom Word tab stops cannot be represented as equal tab intervals. Tab characters are preserved, but their alignment needs review.'; if (!warnings.includes(message)) warnings.push(message); };
  if (settings && elements(settings, 'defaultTabStop').length && !validTabInterval(defaultTabs)) warnTabs();
  for (const paragraph of elements(xml,'p')) {
    const style = attr(first(first(paragraph,'pPr'),'pStyle'));
    if (/^VDocStaticChecklistH[0-6]$/.test(style || '')) {
      const message = 'This Word file contains static checklist symbols. Interactive checkboxes and checklist settings are not restored; use a VDoc backup to preserve them.';
      if (!warnings.includes(message)) warnings.push(message);
    }
  }
  // Mammoth keeps list structure but omits explicit starting numbers.
  const numberingRaw = await zip.file('word/numbering.xml')?.async('string');
  if (numberingRaw) {
    const numbering = new DOMParser().parseFromString(numberingRaw, 'application/xml');
    const numbers = new Map(elements(numbering,'num').map(n=>[attr(n,'numId'),n]));
    const definitions = new Map(elements(numbering,'abstractNum').map(n=>[attr(n,'abstractNumId'),n]));
    const counters = new Map<string,number>();
    const paragraphs: {text:string; start:number; key:string; style:string; bullet:boolean; prefix:string; suffix:string; customBullet:string|null}[] = [];
    for (const paragraph of elements(xml,'p')) {
      // pPrChange contains historical formatting, not the current list id.
      const props = child(child(paragraph,'pPr'),'numPr');
      const id = attr(child(props,'numId')), level = attr(child(props,'ilvl')) || '0';
      const number = numbers.get(id), definition = definitions.get(attr(first(number,'abstractNumId')));
      const override = number && elements(number,'lvlOverride').find(n=>attr(n,'ilvl')===level);
      const settings = first(override,'lvl') || (definition && elements(definition,'lvl').find(n=>attr(n,'ilvl')===level));
      if (!id || !settings) continue;
      const format = attr(first(settings,'numFmt')), marker = attr(first(settings,'lvlText'));
      const bullet = format === 'bullet';
      const types:Record<string,string> = {decimal:'1',lowerLetter:'a',upperLetter:'A',lowerRoman:'i',upperRoman:'I'};
      const bulletStyle = Object.entries(bulletGlyphs).find(([,glyph])=>glyph===marker)?.[0];
      const style = bullet ? bulletStyle || 'disc' : orderedStyle(types[format || '']);
      const placeholder = `%${Number(level)+1}`, parts = marker?.split(placeholder);
      const supportedAffix = parts?.length === 2 && validNumberAffix(parts[0]) && validNumberAffix(parts[1]);
      const prefix = supportedAffix ? parts![0] : '', suffix = supportedAffix ? parts![1] : '.';
      const customBullet = bullet && !bulletStyle && validBulletText(marker) ? marker : null;
      if ((bullet && !bulletStyle && !customBullet) || (!bullet && (!types[format || ''] || !supportedAffix))) {
        const message = 'Some Word list marker formats are not supported. List text and numbering are preserved, but marker appearance needs review.';
        if(!warnings.includes(message))warnings.push(message);
      }
      const start = Number(attr(first(override,'startOverride')) ?? attr(first(settings,'start')) ?? 1);
      const key = `${id}:${level}`, value = (counters.get(key) ?? (start - 1)) + 1;
      counters.set(key,value);
      for (const other of counters.keys()) if (other.startsWith(`${id}:`) && +other.split(':')[1] > +level) counters.delete(other);
      paragraphs.push({text:wordText(paragraph),start:value,key,style,bullet,prefix,suffix,customBullet});
    }
    // Match each direct list item, not just the first item in a list. Mammoth can
    // combine adjacent Word lists with different numbering IDs into one <ol>.
    const itemNumbers = new Map<Element, typeof paragraphs[number]>();
    let cursor = 0;
    for (const item of Array.from(html.querySelectorAll('ol > li, ul > li'))) {
      if (item.hasAttribute('id')) continue;
      const firstParagraph = Array.from(item.children).find(n => /^(P|H[1-6])$/.test(n.tagName));
      const text = firstParagraph ? inlineText(firstParagraph).trim() : undefined;
      const index = paragraphs.findIndex((p, i) => i >= cursor && p.text.trim() === text);
      if (index >= 0) { itemNumbers.set(item, paragraphs[index]); cursor = index + 1; }
    }
    for (const list of Array.from(html.querySelectorAll('ol, ul'))) {
      let current = list, last: typeof paragraphs[number] | undefined;
      for (const item of Array.from(list.children)) {
        const number = itemNumbers.get(item);
        if (last && number && (number.key !== last.key || number.start !== last.start + 1)) {
          const next = list.cloneNode(false) as HTMLOListElement;
          next.removeAttribute('id'); next.removeAttribute('data-block-id');
          current.parentNode!.insertBefore(next, current.nextSibling); current = next; last = undefined;
        }
        if (current !== list) current.appendChild(item);
        if (!last && number) {
          (current as HTMLElement).style.listStyleType = number.style;
          if (number.bullet) {
            if(number.customBullet)current.setAttribute('data-bullet-text',number.customBullet);else current.removeAttribute('data-bullet-text');
          } else {
            if(validListStart(number.start))current.setAttribute('start', String(number.start));
            current.setAttribute('data-number-prefix',number.prefix);current.setAttribute('data-number-suffix',number.suffix);
          }
        }
        last = number;
      }
    }
    const previous = new Map<Element, {key:string; end:number}>();
    for (const list of Array.from(html.querySelectorAll('ol'))) {
      const first = list.firstElementChild && itemNumbers.get(list.firstElementChild), parent = list.parentElement;
      if (!first || !parent) continue;
      const prior = previous.get(parent);
      if (prior?.key === first.key && prior.end === first.start) list.setAttribute('data-continue-numbering', 'true');
      previous.set(parent, { key: first.key, end: first.start + list.children.length });
    }
  }
  const WP = 'http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing';
  const drawings = elements(xml, 'drawing'), images = Array.from(html.body.querySelectorAll('img'));
  // Do not misassign metadata if an unsupported image was omitted by conversion.
  if (drawings.length === images.length) drawings.forEach((drawing, index) => {
    const extent = drawing.getElementsByTagNameNS(WP, 'extent')[0];
    const properties = drawing.getElementsByTagNameNS(WP, 'docPr')[0];
    const width = Number(extent?.getAttribute('cx')) / 9525;
    if (Number.isFinite(width) && width > 0 && width <= 10000) images[index].setAttribute('width', String(Math.round(width)));
    const height = Number(extent?.getAttribute('cy')) / 9525;
    if (Number.isFinite(height) && height > 0 && height <= 10000) images[index].setAttribute('height', String(Math.round(height)));
    const description = properties?.getAttribute('descr');
    if (description) images[index].setAttribute('alt', description);
  });
  // Word emits empty paragraphs inside vertical-merge continuation cells.
  // Mammoth omits those cells entirely. They must not consume a later real
  // empty paragraph (or the paragraph carrying an explicit page break).
  const xmlParagraphs = elements(xml, 'p').filter(paragraph => {
    for (let ancestor = paragraph.parentElement; ancestor; ancestor = ancestor.parentElement) {
      if (ancestor.namespaceURI !== W || ancestor.localName !== 'tc') continue;
      const merge = child(child(ancestor, 'tcPr'), 'vMerge');
      if (merge && attr(merge) !== 'restart') return false;
    }
    return true;
  });
  const htmlParagraphs = Array.from(html.body.querySelectorAll('p,h1,h2,h3,h4,h5,h6,pre')).filter(p => !p.closest('li[id^="footnote-"]'));
  // Match text in sequence; ignore generated footnote reference labels.
  const paragraphTexts = htmlParagraphs.map(inlineText);
  let cursor = 0;
  for (const xp of xmlParagraphs) {
    const text = wordText(xp);
    let hp: Element | undefined;
    for (let i = cursor; i < Math.min(cursor + 8, htmlParagraphs.length); i++) {
      if (paragraphTexts[i] === text) { hp = htmlParagraphs[i]; cursor = i + 1; break; }
    }
    if (!hp) continue;
    const properties = child(xp, 'pPr'), inherited = paragraphProperties(xp);
    // Numbering conversion must preserve list containers; restore heading
    // semantics afterwards from the effective Word outline level, not its name.
    const outline = inherited.outlineLvl?.val;
    if (outline !== undefined && /^(P|H[1-6])$/.test(hp.tagName)) {
      if (/^[0-5]$/.test(outline) || outline === '9') {
        const tag = outline === '9' ? 'p' : `h${Number(outline) + 1}`;
        if (hp.tagName.toLowerCase() !== tag) {
          const replacement = html.createElement(tag);
          for (const attribute of Array.from(hp.attributes)) replacement.setAttribute(attribute.name, attribute.value);
          for (const node of Array.from(hp.childNodes)) replacement.appendChild(node);
          hp.replaceWith(replacement); hp = replacement;
        }
      } else {
        const message = 'Some Word outline levels are unsupported. Their text is preserved; review heading levels after import.';
        if (!warnings.includes(message)) warnings.push(message);
      }
    }
    const target = hp as HTMLElement;
    restoreParagraphDecoration(target, inherited, theme, warnings);
    restoreParagraphFlags(target, inherited, warnings);
    restoreParagraphSpacing(target, inherited.spacing || {}, warnings);
    const rtl=target.getAttribute('dir')==='rtl';
    // Store the offset relative to VDoc's 24px per list level, not the source
    // numbering definition (which can have a different physical indentation).
    let listStart = 0;
    for (let ancestor = target.parentElement; ancestor; ancestor = ancestor.parentElement) {
      if (ancestor.tagName === 'UL' || ancestor.tagName === 'OL' || ancestor.tagName === 'BLOCKQUOTE' && ancestor.hasAttribute('data-vdoc-word-quote')) listStart += 24;
      if (ancestor.tagName === 'TD' || ancestor.tagName === 'TH') break;
    }
    const special = restoreParagraphIndent(target, inherited.ind || {}, listStart, warnings);
    let interval = defaultInterval;
    const stops = first(properties, 'tabs');
    if (stops) {
      const tabs = elements(stops, 'tab'), positions = tabs.map(tab => Number(attr(tab, 'pos')) / 15);
      const step = positions[1] - positions[0];
      const origin = Number(target.getAttribute('data-indent-start') || 0) + Math.max(0, -special) + listStart;
      if (positions.length >= 2 && validTabInterval(Math.round(step)) && Math.abs(step - Math.round(step)) < 0.05 && tabs.every(tab => ['start', rtl ? 'right' : 'left'].includes(attr(tab) || '') && (!attr(tab, 'leader') || attr(tab, 'leader') === 'none')) && positions.every((position, i) => Math.abs(position - origin - (i + 1) * Math.round(step)) < 0.05)) interval = Math.round(step);
      else if (tabs.length) warnTabs();
    }
    target.setAttribute('data-tab-interval', String(interval));
    target.style.tabSize = `${interval}px`;
    target.style.whiteSpace = 'pre-wrap';
    const pageBreaks = elements(xp, 'br').filter(br => attr(br, 'type') === 'page');
    if (pageBreaks.length) {
      const markers = html.createDocumentFragment();
      for (const _break of pageBreaks) { const marker = html.createElement('div'); marker.setAttribute('data-page-break',''); markers.appendChild(marker); }
      // A standalone break is a block in VDoc, not an empty paragraph plus a
      // break. Replacing the carrier prevents blank paragraphs accumulating on
      // repeated export/import. Preserve meaningful inline objects otherwise.
      if (!hp.childNodes.length) hp.replaceWith(markers);
      else hp.parentNode!.insertBefore(markers, hp.nextSibling);
    }
    const runs = elements(xp, 'r');
    if (!runs.length || !text) continue;
    if (!restoreInlineRuns(html, target, runs, (run, text) => formatRun(html, run, xp, text, /^H[1-6]$/.test(target.tagName) || !!target.closest('th')))) {
      const message = 'Some Word text formatting could not be matched to the converted text. Links and references are preserved, but formatting needs review.';
      if (!warnings.includes(message)) warnings.push(message);
    }
  }

  const xtables = elements(xml, 'tbl'), htables = Array.from(html.body.querySelectorAll('table'));
  xtables.forEach((table, index) => {
    const bidi = child(child(table,'tblPr'),'bidiVisual');
    htables[index]?.setAttribute('dir', bidi && !['0','false','off'].includes(attr(bidi) || '1') ? 'rtl' : 'ltr');
    const alignment = attr(child(child(table,'tblPr'),'jc'));
    if (alignment && ['left','center','right'].includes(alignment)) htables[index]?.setAttribute('data-table-align',alignment);
    const belongsToTable = (el: Element) => { let parent = el.parentElement; while (parent && !(parent.namespaceURI === W && parent.localName === 'tbl')) parent = parent.parentElement; return parent === table; };
    const xrows = elements(table, 'tr').filter(belongsToTable), hrows = htables[index]?.rows;
    let pinnedRows = 0;
    for (const row of xrows) {
      const flag = child(Array.from(row.children).find(n => n.localName === 'trPr'), 'tblHeader');
      if (!flag || ['0','false','off'].includes(attr(flag) || '1')) break;
      pinnedRows++;
    }
    htables[index]?.setAttribute('data-pinned-rows', String(pinnedRows));
    xrows.forEach((row, i) => {
      const target = hrows?.[i]; if (!target) return;
      const rowProps = Array.from(row.children).find(n => n.localName === 'trPr');
      const height = +(attr(child(rowProps, 'trHeight')) || 0);
      if (height > 0) target.style.height = `${height / 15}px`;
      const noSplit = child(rowProps, 'cantSplit');
      target.setAttribute('data-allow-split', String(!noSplit || ['0','false','off'].includes(attr(noSplit) || '1')));
      const flag = child(rowProps, 'tblHeader');
      const tag = flag && !['0','false','off'].includes(attr(flag) || '1') ? 'th' : 'td';
      Array.from(target.cells).forEach(cell => {
        if (cell.tagName.toLowerCase() === tag) return;
        const replacement = html.createElement(tag);
        for (const a of Array.from(cell.attributes)) replacement.setAttribute(a.name, a.value);
        while (cell.firstChild) replacement.appendChild(cell.firstChild);
        cell.parentNode!.replaceChild(replacement, cell);
      });
    });
    const grid = Array.from(child(table,'tblGrid')?.children || []).map(col=>+(attr(col,'w') || 0));
    const gridWidths = new Map<Element, number[]>();
    for (const row of xrows) {
      let column = 0;
      for (const cell of Array.from(row.children).filter(n=>n.localName === 'tc')) {
        const span = +(attr(child(child(cell,'tcPr'),'gridSpan')) || 1);
        gridWidths.set(cell,grid.slice(column,column + span)); column += span;
      }
    }
    // Word includes placeholder cells for vertical-merge continuation rows.
    // Mammoth folds them into the starting cell's rowspan and emits no HTML
    // cell for them. Match only visible starting cells, keeping the full grid
    // above so widths after a continuation still use the correct columns.
    const cells = elements(table, 'tc').filter(belongsToTable).filter(cell => {
      const merge = child(child(cell, 'tcPr'), 'vMerge');
      return !merge || attr(merge) === 'restart';
    }), htmlCells = htables[index] ? Array.from(htables[index].querySelectorAll('td,th')).filter(cell => cell.closest('table') === htables[index]) : undefined; if (!htmlCells || cells.length !== htmlCells.length) return;
    cells.forEach((cell, i) => {
      const tc = child(cell, 'tcPr'), hc = htmlCells[i] as HTMLElement;
      const shading = child(tc, 'shd') || child(child(cell.parentElement || undefined, 'tblPrEx'), 'shd') || child(child(table, 'tblPr'), 'shd');
      if (shading) hc.style.backgroundColor = wordShading(wordAttributes(shading), theme, warnings) || '';
      const alignment = attr(child(tc,'vAlign')); if (alignment) hc.style.verticalAlign = alignment === 'center' ? 'middle' : alignment;
      const borders = child(tc,'tcBorders');
      for (const side of ['top','right','bottom','left']) {
        const edge = child(borders,side); if (!edge) continue;
        const style = attr(edge), color = validHex(attr(edge,'color')), size = attr(edge,'sz');
        hc.style.setProperty(`border-${side}-style`,style === 'dashed' ? 'dashed' : style === 'dotted' ? 'dotted' : 'solid');
        if (color) hc.style.setProperty(`border-${side}-color`,color);
        if (style === 'nil' || style === 'none') hc.style.setProperty(`border-${side}-width`,'0px');
        else if (size) hc.style.setProperty(`border-${side}-width`,`${+size / 6}px`);
      }
      const padding = attr(child(child(tc,'tcMar'),'left'),'w'); if (padding) hc.style.padding = `${+padding / 15}px`;
      const width = child(tc, 'tcW'), span = +(attr(child(tc, 'gridSpan')) || 1);
      const dxa = +(attr(width, 'w') || 0);
      if (attr(width, 'type') === 'dxa' && dxa > 0 && span >= 1 && span <= 100) {
        const widths = gridWidths.get(cell) || [];
        const matchesGrid = widths.length === span && widths.every(n=>n > 0) && Math.abs(widths.reduce((a,b)=>a+b,0) - dxa) < 2;
        hc.setAttribute('colwidth', (matchesGrid ? widths.map(n=>Math.max(1,Math.round(n / 15))) : Array(span).fill(Math.max(1, Math.round(dxa / 15 / span)))).join(','));
      }
      const rowHeight = cell.parentElement ? child(child(cell.parentElement, 'trPr'), 'trHeight') : undefined;
      const height = +(attr(rowHeight) || 0); if (height > 0) hc.style.height = `${height / 15}px`;
    });
  });
  const section = elements(xml, 'sectPr').at(-1), page = first(section,'pgSz'), margins = first(section,'pgMar');
  const width = +(attr(page,'w') || 11906), height = +(attr(page,'h') || 16838);
  const pageMargin = Math.round(+(attr(margins,'left') || 1134) / 56.693);
  const relRaw = await zip.file('word/_rels/document.xml.rels')?.async('string');
  const relationships = relRaw ? new DOMParser().parseFromString(relRaw, 'application/xml') : null;
  let header = '', footer = '', pageNumbers = false;
  for (const kind of ['header','footer']) {
    const reference = first(section,`${kind}Reference`), id = reference?.getAttributeNS('http://schemas.openxmlformats.org/officeDocument/2006/relationships','id');
    const relation = Array.from(relationships?.getElementsByTagName('Relationship') || []).find(r=>r.getAttribute('Id') === id);
    const path = relation?.getAttribute('Target'); if (!path || relation?.getAttribute('TargetMode') === 'External') continue;
    const source = await zip.file(path.startsWith('/') ? path.slice(1) : `word/${path}`)?.async('string'); if (!source) continue;
    const document = new DOMParser().parseFromString(source, 'application/xml');
    const text = elements(document, 'p').map(p=>elements(p,'t').map(t=>t.textContent || '').join('')).join('\n').trim();
    if (kind === 'header') header = text; else { footer = text; pageNumbers = elements(document,'instrText').some(t=>/\bPAGE\b/.test(t.textContent || '')); }
  }
  return { language, header, footer, pageNumbers, pageSize: Math.abs(Math.min(width,height) - 12240) < 100 ? 'letter' : 'a4', orientation: attr(page,'orient') === 'landscape' ? 'landscape' : 'portrait', pageMargin: Math.max(5,Math.min(50,pageMargin)) };
}
