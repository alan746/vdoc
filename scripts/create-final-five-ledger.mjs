function add(gate, group, title, setup, action, expected, evidence, depends = []) {
  const n = rows.filter(r => r.gate === gate).length + 1;
  const id = `${gate}${String(n).padStart(3, '0')}`;
  rows.push({ id, order: rows.length + 1, gate, group, title, setup, action, expected,
    evidenceRequired: evidence, depends, owner: 'Codex', status: '待执行',
    result: '', evidence: '', blocker: '', next: `执行 ${id}，记录实际结果及证据`, verifiedAt: '' });
}
function block(gate, group, setup, lines, evidence, depends = []) {
  for (const line of lines.trim().split('\n')) {
    const fields = line.split('|');
    if (fields.length !== 3) throw new Error(line);
    add(gate, group, ...[fields[0], setup, fields[1], fields[2], evidence, depends]);
  }
}

